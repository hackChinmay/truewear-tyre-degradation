export interface TrackPointTelemetry {
  name: string;
  x: number;
  y: number;
  sector: 1 | 2 | 3;
  speed: number; // km/h
  gear: number; // 1-8
  throttle: number; // 0-100%
  brake: number; // 0-100%
  drs: boolean;
  steeringAngle: number; // degrees
}

export interface CornerAnnotation {
  name: string;
  turnNumber?: string;
  x: number;
  y: number;
  note: string;
  labelDx?: number;
  labelDy?: number;
}

export interface DrsZoneConfig {
  id: string;
  label: string;
  path: string;
  labelX: number;
  labelY: number;
}

export interface CircuitTrackConfig {
  id: string;
  name: string;
  formalName: string;
  location: string;
  country: string;
  lengthKm: number;
  totalLaps: number;
  viewBox: string;
  trackPath: string;
  pitLanePath: string;
  startFinishLine: {
    x1: number;
    y1: number;
    x2: number;
    y2: number;
    labelX: number;
    labelY: number;
  };
  pitBoxCoord: {
    x: number;
    y: number;
  };
  drsZones: DrsZoneConfig[];
  corners: CornerAnnotation[];
  waypoints: TrackPointTelemetry[];
}

