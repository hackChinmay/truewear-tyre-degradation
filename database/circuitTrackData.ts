export function getCircuitTrackTelemetry(circuitId: string, progress: number): TrackPointTelemetry {
  const config = getCircuitConfig(circuitId);
  const clampedProgress = ((progress % 1) + 1) % 1;
  const index = Math.floor(clampedProgress * (config.waypoints.length - 1));
  const nextIndex = Math.min(index + 1, config.waypoints.length - 1);
  const factor = (clampedProgress * (config.waypoints.length - 1)) - index;

  const current = config.waypoints[index];
  const next = config.waypoints[nextIndex];

  return {
    name: current.name,
    x: Number((current.x + (next.x - current.x) * factor).toFixed(1)),
    y: Number((current.y + (next.y - current.y) * factor).toFixed(1)),
    sector: current.sector,
    speed: Math.round(current.speed + (next.speed - current.speed) * factor),
    gear: current.gear,
    throttle: Math.round(current.throttle + (next.throttle - current.throttle) * factor),
    brake: Math.round(current.brake + (next.brake - current.brake) * factor),
    drs: current.drs,
    steeringAngle: Number((current.steeringAngle + (next.steeringAngle - current.steeringAngle) * factor).toFixed(1)),
  };
}
